-- Phase 1 PostgreSQL schema reference for AutoParts Business Analytics.
-- Apply through versioned Alembic migrations during Phase 2; do not use this
-- file to reset or overwrite an existing business database.

BEGIN;

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE CHECK (name IN ('owner', 'staff')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    username VARCHAR(80) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    full_name VARCHAR(160) NOT NULL,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    brand VARCHAR(100) NOT NULL,
    compatible_vehicle_make VARCHAR(100),
    vehicle_model VARCHAR(100),
    part_number VARCHAR(100) UNIQUE,
    barcode VARCHAR(100) UNIQUE,
    description TEXT,
    unit_cost_lkr NUMERIC(14, 2) NOT NULL CHECK (unit_cost_lkr >= 0),
    retail_price_lkr NUMERIC(14, 2) NOT NULL CHECK (retail_price_lkr >= 0),
    wholesale_price_lkr NUMERIC(14, 2) NOT NULL CHECK (wholesale_price_lkr >= 0),
    reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    data_origin VARCHAR(20) NOT NULL DEFAULT 'business'
        CHECK (data_origin IN ('business', 'synthetic_demo')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    customer_type VARCHAR(20) NOT NULL CHECK (customer_type IN ('retail', 'wholesale')),
    contact_number VARCHAR(40),
    email VARCHAR(254),
    address TEXT,
    city VARCHAR(100),
    district VARCHAR(100),
    province VARCHAR(100),
    opening_balance_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (opening_balance_lkr >= 0),
    registered_at DATE NOT NULL DEFAULT CURRENT_DATE,
    data_origin VARCHAR(20) NOT NULL DEFAULT 'business'
        CHECK (data_origin IN ('business', 'synthetic_demo')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    company_name VARCHAR(200),
    contact_person VARCHAR(160),
    contact_number VARCHAR(40),
    email VARCHAR(254),
    address TEXT,
    city VARCHAR(100),
    district VARCHAR(100),
    province VARCHAR(100),
    supplier_type VARCHAR(80),
    payment_terms VARCHAR(100),
    opening_balance_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (opening_balance_lkr >= 0),
    registered_at DATE NOT NULL DEFAULT CURRENT_DATE,
    data_origin VARCHAR(20) NOT NULL DEFAULT 'business'
        CHECK (data_origin IN ('business', 'synthetic_demo')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(60) NOT NULL UNIQUE,
    idempotency_key VARCHAR(80) UNIQUE,
    request_fingerprint VARCHAR(64),
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    sale_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    sale_type VARCHAR(20) NOT NULL CHECK (sale_type IN ('retail', 'wholesale')),
    status VARCHAR(20) NOT NULL DEFAULT 'completed'
        CHECK (status IN ('draft', 'completed', 'cancelled', 'partially_returned', 'returned')),
    subtotal_lkr NUMERIC(14, 2) NOT NULL CHECK (subtotal_lkr >= 0),
    discount_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (discount_lkr >= 0),
    total_amount_lkr NUMERIC(14, 2) NOT NULL CHECK (total_amount_lkr >= 0),
    notes TEXT,
    data_origin VARCHAR(20) NOT NULL DEFAULT 'business'
        CHECK (data_origin IN ('business', 'synthetic_demo')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (discount_lkr <= subtotal_lkr),
    CHECK (total_amount_lkr = subtotal_lkr - discount_lkr)
);

CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_lkr NUMERIC(14, 2) NOT NULL CHECK (unit_price_lkr >= 0),
    unit_cost_lkr NUMERIC(14, 2) NOT NULL CHECK (unit_cost_lkr >= 0),
    discount_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (discount_lkr >= 0),
    line_total_lkr NUMERIC(14, 2) NOT NULL CHECK (line_total_lkr >= 0),
    gross_profit_lkr NUMERIC(14, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (discount_lkr <= quantity * unit_price_lkr),
    CHECK (line_total_lkr = quantity * unit_price_lkr - discount_lkr)
);

CREATE TABLE purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_number VARCHAR(60) NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
    supplier_invoice_number VARCHAR(100),
    purchase_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    status VARCHAR(24) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'ordered', 'partially_received', 'received', 'cancelled')),
    subtotal_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (subtotal_lkr >= 0),
    discount_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (discount_lkr >= 0),
    total_cost_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (total_cost_lkr >= 0),
    notes TEXT,
    data_origin VARCHAR(20) NOT NULL DEFAULT 'business'
        CHECK (data_origin IN ('business', 'synthetic_demo')),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (discount_lkr <= subtotal_lkr),
    CHECK (total_cost_lkr = subtotal_lkr - discount_lkr),
    UNIQUE (supplier_id, supplier_invoice_number)
);

CREATE TABLE purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES purchases(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity_ordered INTEGER NOT NULL CHECK (quantity_ordered > 0),
    quantity_received INTEGER NOT NULL DEFAULT 0 CHECK (quantity_received >= 0),
    unit_cost_lkr NUMERIC(14, 2) NOT NULL CHECK (unit_cost_lkr >= 0),
    discount_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (discount_lkr >= 0),
    line_total_lkr NUMERIC(14, 2) NOT NULL CHECK (line_total_lkr >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (quantity_received <= quantity_ordered),
    CHECK (discount_lkr <= quantity_ordered * unit_cost_lkr),
    CHECK (line_total_lkr = quantity_ordered * unit_cost_lkr - discount_lkr)
);

CREATE TABLE inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL UNIQUE REFERENCES products(id) ON DELETE RESTRICT,
    current_stock INTEGER NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
    minimum_stock_level INTEGER NOT NULL DEFAULT 0 CHECK (minimum_stock_level >= 0),
    maximum_stock_level INTEGER NOT NULL DEFAULT 0 CHECK (maximum_stock_level >= minimum_stock_level),
    weighted_average_cost_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (weighted_average_cost_lkr >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE RESTRICT,
    amount_lkr NUMERIC(14, 2) NOT NULL CHECK (amount_lkr > 0),
    payment_method VARCHAR(24) NOT NULL
        CHECK (payment_method IN ('cash', 'card', 'bank_transfer', 'other')),
    payment_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    reference_number VARCHAR(120),
    received_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'recorded' CHECK (status IN ('recorded', 'voided')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE supplier_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
    purchase_id BIGINT REFERENCES purchases(id) ON DELETE RESTRICT,
    amount_lkr NUMERIC(14, 2) NOT NULL CHECK (amount_lkr > 0),
    payment_method VARCHAR(24) NOT NULL
        CHECK (payment_method IN ('cash', 'card', 'bank_transfer', 'other')),
    payment_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    reference_number VARCHAR(120),
    recorded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number VARCHAR(60) NOT NULL UNIQUE,
    return_type VARCHAR(16) NOT NULL CHECK (return_type IN ('sale', 'purchase')),
    sale_id BIGINT REFERENCES sales(id) ON DELETE RESTRICT,
    purchase_id BIGINT REFERENCES purchases(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'completed' CHECK (status IN ('pending', 'completed', 'rejected')),
    reason TEXT NOT NULL,
    return_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    total_amount_lkr NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (total_amount_lkr >= 0),
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (return_type = 'sale' AND sale_id IS NOT NULL AND purchase_id IS NULL)
        OR (return_type = 'purchase' AND purchase_id IS NOT NULL AND sale_id IS NULL)
    )
);

CREATE TABLE return_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT NOT NULL REFERENCES returns(id) ON DELETE RESTRICT,
    sale_item_id BIGINT REFERENCES sale_items(id) ON DELETE RESTRICT,
    purchase_item_id BIGINT REFERENCES purchase_items(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    resalable BOOLEAN NOT NULL DEFAULT FALSE,
    amount_lkr NUMERIC(14, 2) NOT NULL CHECK (amount_lkr >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (sale_item_id IS NOT NULL AND purchase_item_id IS NULL)
        OR (purchase_item_id IS NOT NULL AND sale_item_id IS NULL)
    )
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    movement_type VARCHAR(24) NOT NULL CHECK (
        movement_type IN ('sale', 'purchase_receipt', 'sales_return', 'purchase_return',
                          'adjustment', 'damage', 'missing')
    ),
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    previous_stock INTEGER NOT NULL CHECK (previous_stock >= 0),
    new_stock INTEGER NOT NULL CHECK (new_stock >= 0),
    sale_item_id BIGINT REFERENCES sale_items(id) ON DELETE RESTRICT,
    purchase_item_id BIGINT REFERENCES purchase_items(id) ON DELETE RESTRICT,
    return_item_id BIGINT REFERENCES return_items(id) ON DELETE RESTRICT,
    reason TEXT,
    recorded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (new_stock = previous_stock + quantity_delta),
    CHECK (
        (CASE WHEN sale_item_id IS NOT NULL THEN 1 ELSE 0 END)
        + (CASE WHEN purchase_item_id IS NOT NULL THEN 1 ELSE 0 END)
        + (CASE WHEN return_item_id IS NOT NULL THEN 1 ELSE 0 END) <= 1
    )
);

CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(80) NOT NULL CHECK (
        category IN ('shop_rent', 'electricity', 'water', 'transport', 'salaries',
                     'repairs_maintenance', 'internet_telephone', 'other')
    ),
    description TEXT NOT NULL,
    amount_lkr NUMERIC(14, 2) NOT NULL CHECK (amount_lkr > 0),
    expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
    payment_method VARCHAR(24) NOT NULL
        CHECK (payment_method IN ('cash', 'card', 'bank_transfer', 'other')),
    recorded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    data_origin VARCHAR(20) NOT NULL DEFAULT 'business'
        CHECK (data_origin IN ('business', 'synthetic_demo')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(80),
    before_data JSONB,
    after_data JSONB,
    ip_address INET,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_sales_date_status ON sales (sale_date, status);
CREATE INDEX idx_sales_customer_date ON sales (customer_id, sale_date);
CREATE INDEX idx_sale_items_product ON sale_items (product_id);
CREATE INDEX idx_purchases_supplier_date ON purchases (supplier_id, purchase_date);
CREATE INDEX idx_purchase_items_product ON purchase_items (product_id);
CREATE INDEX idx_stock_movements_product_date ON stock_movements (product_id, occurred_at);
CREATE INDEX idx_payments_sale_date ON payments (sale_id, payment_date);
CREATE INDEX idx_expenses_date_category ON expenses (expense_date, category);
CREATE INDEX idx_returns_date ON returns (return_date);
CREATE INDEX idx_audit_logs_entity ON audit_logs (entity_type, entity_id, occurred_at);

INSERT INTO roles (name) VALUES ('owner'), ('staff')
ON CONFLICT (name) DO NOTHING;

COMMIT;
